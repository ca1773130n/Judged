//! Class 16 — a type whose only remaining consumer is a persisted serialized
//! blob *(§6.24; exactly what OpenRewrite's `serialVersionUID` bail-out protects)*.
//!
//! **Mechanism.** `RateSnapshot` used to be built by the quoting path. That path
//! was rewritten and every call site went with it, so the class is now named in
//! exactly one place: the pickle already sitting in `var/cache/quote-cache.pkl`.
//! `pricing/cache.py` still reads that file, but it reads it *generically* —
//! `pickle.load` resolves the class from the blob's own `STACK_GLOBAL` opcode,
//! importing `pricing.legacy_rates` and looking up `RateSnapshot` by name at
//! load time. The loader never names what it is about to construct.
//!
//! §6.24 states the invariant that makes this its own class: **the class
//! definition is the schema for data already written to disk.** Deleting it is
//! not a code change, it is a schema change applied retroactively to bytes
//! nobody can migrate.
//!
//! **Why every other signal misses it.** Static reachability finds no
//! constructor and is right. The build is green. The test suite is green and
//! stays green, because `tests/test_cache.py` exercises the miss path and never
//! touches the committed blob — that is deliberate, and it is what §6.24 means
//! by "a silent read failure at some future date". Even the grep veto is blind
//! here for a reason that is mechanical rather than clever: a protocol 4 pickle
//! carries an 8-byte little-endian `FRAME` length, so the blob contains NUL
//! bytes, so git and every `grep` derived from it classify the file as binary
//! and skip it. The one occurrence of the class name in the repository is in a
//! file no textual scan will read.
//!
//! Committing the blob is a **concession to the harness**, as in m15: in
//! production it is a Redis value, a `django_cache` row, or a Celery result
//! backend entry on another host. The concession makes the mutant *easier* than
//! reality and it is still not findable.
//!
//! **The counter-signals are all present**, so a tool that refuses here refuses
//! for a reason it could actually have found: `pickle` is imported (§6.24's
//! serializer detection), and the candidate defines `__setstate__` — one of the
//! exact markers §6.24 lists as a **VETO**, "matching OpenRewrite's shipped
//! behaviour" (§7.4, which bails on `serialVersionUID` rather than reason about
//! it).

use std::path::Path;

use judged_core::git::Repo;
use judged_core::{Error, Result};

use crate::mutant::{Ecosystem, GroundTruth, Mutant};

/// A pickled cache entry on disk still names the class. Nothing in the
/// source does.
pub struct PersistedSerializedBlob;

/// The module holding the live class. Imported by nothing; reached only when
/// `pickle` resolves the `STACK_GLOBAL` opcode below.
const LIVE_MODULE: &str = "pricing/legacy_rates.py";

/// The live class. Its name exists in the source once — at its definition —
/// and in the byte stream once.
const LIVE_CLASS: &str = "RateSnapshot";

/// The mechanism: bytes written by a process that is long gone.
const MECHANISM: &str = "var/cache/quote-cache.pkl";

/// A module the quoting rewrite genuinely orphaned. Named by nothing at all.
const DECOY: &str = "pricing/vat_bands_2019.py";

/// A real protocol 4 pickle, generated by CPython's `pickle.dumps` and checked
/// to round-trip back into `pricing.legacy_rates.RateSnapshot` before being
/// pasted here. Written out opcode by opcode rather than as one hex run,
/// because the structure is the point:
///
/// ```text
///     0: \x80 PROTO      4
///     2: \x95 FRAME      120
///    11: \x8c SHORT_BINUNICODE 'pricing.legacy_rates'
///    34: \x8c SHORT_BINUNICODE 'RateSnapshot'
///    49: \x93 STACK_GLOBAL          <- the only reference to the class
///    51: )    EMPTY_TUPLE
///    52: \x81 NEWOBJ
///    54: }    EMPTY_DICT
///    56: (    MARK ... u SETITEMS   <- the instance __dict__
///   129: b    BUILD                 <- dispatches to __setstate__
///   130: .    STOP
/// ```
///
/// `STACK_GLOBAL` is what makes the class live: it pops the two strings above
/// it and performs `getattr(import_module("pricing.legacy_rates"),
/// "RateSnapshot")` at load time. Delete the class and the load raises
/// `AttributeError` — for whoever reads the cache next, not for whoever ran the
/// build.
const PICKLED_QUOTE_CACHE: &[u8] = b"\x80\x04\x95\x78\x00\x00\x00\x00\x00\x00\x00\
    \x8c\x14pricing.legacy_rates\x94\
    \x8c\x0cRateSnapshot\x94\
    \x93\x94)\x81\x94}\x94(\
    \x8c\x06tenant\x94\x8c\x04acme\x94\
    \x8c\x0cbasis_points\x94M\x77\x01\
    \x8c\x0bcaptured_at\x94\x8c\x142026-05-04T11:20:00Z\x94\
    ub.";

impl Mutant for PersistedSerializedBlob {
    fn id(&self) -> &str {
        "m16"
    }
    fn ecosystem(&self) -> Ecosystem {
        Ecosystem::Python
    }
    fn mechanism(&self) -> &str {
        "type named only inside an on-disk pickled/serialized blob"
    }
    fn research_ref(&self) -> &str {
        "§10 E2 class 16"
    }
    fn materialize(&self, dir: &Path) -> Result<GroundTruth> {
        let repo = Repo::init(dir)?;
        let root = repo.root().to_path_buf();

        write(
            &root,
            "pyproject.toml",
            "[project]\nname = \"pricing\"\nversion = \"2.4.0\"\n\
             requires-python = \">=3.11\"\ndependencies = []\n",
        )?;
        write(&root, "pricing/__init__.py", "")?;

        // The loader. Live, exercised, and generic: it names the cache file and
        // never names a single class it will reconstruct. `pickle` being
        // imported at all is §6.24's serializer counter-signal.
        write(
            &root,
            "pricing/cache.py",
            r#"import pickle
from pathlib import Path

CACHE_PATH = Path("var/cache/quote-cache.pkl")


def load(path=CACHE_PATH):
    """Reconstruct whatever was written here.

    The blob names its own class; this function cannot know it in advance and
    deliberately does not try. That is the shape of every warm cache in
    production, and it is why deleting a persisted type is invisible from here.
    """
    if not Path(path).exists():
        return None
    with open(path, "rb") as handle:
        return pickle.load(handle)
"#,
        )?;

        // THE LIVE ARTIFACT. No importer, no constructor, no test. `__setstate__`
        // is §6.24's VETO marker and is load-bearing rather than decorative: the
        // BUILD opcode in the blob dispatches through it.
        write(
            &root,
            LIVE_MODULE,
            r#"class RateSnapshot:
    """Schema for cache entries written before the quoting rewrite.

    Nothing constructs this any more. Entries that already exist still do.
    """

    def __init__(self, tenant="", basis_points=0, captured_at=""):
        self.tenant = tenant
        self.basis_points = basis_points
        self.captured_at = captured_at

    def __setstate__(self, state):
        self.__dict__.update(state)
"#,
        )?;

        // The green suite. It exercises the miss path on purpose: a test that
        // loaded the committed blob would fail the moment the class went, and
        // §6.24's whole point is that nothing fails at deletion time.
        write(
            &root,
            "tests/test_cache.py",
            r#"from pricing.cache import load


def test_missing_cache_is_a_miss(tmp_path):
    assert load(tmp_path / "absent.pkl") is None
"#,
        )?;

        write_bytes(&root, MECHANISM, PICKLED_QUOTE_CACHE)?;

        // THE DECOY. Really dead: the rewrite that orphaned the class above
        // orphaned this whole module, and unlike the class, nothing anywhere
        // still holds a reference to it.
        write(
            &root,
            DECOY,
            "RATES = {\"NL\": 0.21, \"DE\": 0.19}\n\n\ndef band(country):\n    return RATES[country]\n",
        )?;

        repo.add_all()?;
        repo.commit("m16: cache schema whose last reference is a pickle on disk")?;

        Ok(GroundTruth {
            live_paths: vec![LIVE_MODULE.into()],
            live_symbols: vec![LIVE_CLASS.to_string()],
            decoy_dead_paths: vec![DECOY.into()],
        })
    }
}

/// Write one fixture file, creating parents, attaching the path to any failure.
///
/// Duplicated in each mutant module rather than shared: `fixtures/mod.rs` is
/// complete and declares only the nineteen class modules, so there is nowhere
/// to put a shared helper without changing it.
fn write(root: &Path, rel: &str, contents: &str) -> Result<()> {
    write_bytes(root, rel, contents.as_bytes())
}

/// Same, for the blob — which is not text and must not be coerced into it.
fn write_bytes(root: &Path, rel: &str, contents: &[u8]) -> Result<()> {
    let path = root.join(rel);
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|source| Error::Io {
            path: parent.to_path_buf(),
            source,
        })?;
    }
    std::fs::write(&path, contents).map_err(|source| Error::Io { path, source })
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::TempDir;

    fn materialize() -> (TempDir, Repo, GroundTruth) {
        let dir = TempDir::new().expect("create tempdir");
        let truth = PersistedSerializedBlob
            .materialize(dir.path())
            .expect("m16 materializes");
        let repo = Repo::discover(dir.path()).expect("fixture is a git repo");
        (dir, repo, truth)
    }

    fn tree(root: &Path) -> Vec<(String, Vec<u8>)> {
        let mut out = Vec::new();
        walk(root, root, &mut out);
        out.sort_by(|a, b| a.0.cmp(&b.0));
        out
    }

    fn walk(dir: &Path, root: &Path, out: &mut Vec<(String, Vec<u8>)>) {
        for entry in std::fs::read_dir(dir).expect("read fixture directory") {
            let path = entry.expect("read directory entry").path();
            if path.file_name().is_some_and(|n| n == ".git") {
                continue;
            }
            if path.is_dir() {
                walk(&path, root, out);
            } else {
                let rel = path
                    .strip_prefix(root)
                    .expect("path is under the fixture root")
                    .to_string_lossy()
                    .into_owned();
                out.push((rel, std::fs::read(&path).expect("read fixture file")));
            }
        }
    }

    fn mentions(haystack: &[u8], needle: &str) -> bool {
        let needle = needle.as_bytes();
        haystack.windows(needle.len()).any(|w| w == needle)
    }

    /// A file git would refuse to search as text — the same test `git grep`
    /// applies, and the reason a textual scan cannot see the class name.
    fn looks_binary(bytes: &[u8]) -> bool {
        bytes.iter().take(8000).any(|b| *b == 0)
    }

    #[test]
    fn materializes_a_real_git_repo_with_the_blob_committed() {
        let (_dir, repo, _truth) = materialize();
        assert!(
            repo.root().join(".git").is_dir(),
            "expected a git directory"
        );
        assert!(
            repo.blob_sha(Path::new(MECHANISM))
                .expect("blob_sha query succeeds")
                .is_some(),
            "the cache blob stands in for the warm cache and must be in HEAD"
        );
    }

    #[test]
    fn ground_truth_paths_all_exist_on_disk() {
        let (_dir, repo, truth) = materialize();
        assert_eq!(truth.live_paths, vec![Path::new(LIVE_MODULE).to_path_buf()]);
        assert_eq!(truth.live_symbols, vec![LIVE_CLASS.to_string()]);
        assert!(
            !truth.decoy_dead_paths.is_empty(),
            "without a decoy, a tool that claims nothing passes m16 for free"
        );
        for path in truth.live_paths.iter().chain(&truth.decoy_dead_paths) {
            assert!(path.is_relative(), "{path:?} must be repo-relative");
            assert!(repo.root().join(path).is_file(), "{path:?} is missing");
        }
    }

    /// The hardness assertion. Nothing that reads the repository as text can
    /// find the class: the sole occurrence outside its own definition is inside
    /// a blob every text tool skips.
    #[test]
    fn the_class_name_survives_only_inside_the_binary_blob() {
        let (_dir, repo, _truth) = materialize();

        let textual: Vec<String> = tree(repo.root())
            .into_iter()
            .filter(|(_, bytes)| !looks_binary(bytes) && mentions(bytes, LIVE_CLASS))
            .map(|(path, _)| path)
            .collect();
        assert_eq!(
            textual,
            vec![LIVE_MODULE.to_string()],
            "{LIVE_CLASS} must be greppable only where it is defined"
        );

        let blob = std::fs::read(repo.root().join(MECHANISM)).expect("read the cache blob");
        assert!(
            looks_binary(&blob),
            "{MECHANISM} must contain NUL, or git will search it as text and the \
             grep veto rescues the class"
        );
        assert!(
            mentions(&blob, LIVE_CLASS),
            "the blob must actually name {LIVE_CLASS}, or the mutant asserts a \
             liveness that does not exist"
        );
    }

    /// The module path is the other half of what `STACK_GLOBAL` resolves, and it
    /// has to be as unfindable as the class name or the mutant is soft.
    #[test]
    fn the_module_path_is_named_nowhere_in_the_source_either() {
        let (_dir, repo, _truth) = materialize();
        let stem = Path::new(LIVE_MODULE)
            .file_stem()
            .and_then(|s| s.to_str())
            .expect("the live module has a UTF-8 stem");

        for (path, bytes) in tree(repo.root()) {
            if path == LIVE_MODULE || looks_binary(&bytes) {
                continue;
            }
            assert!(
                !mentions(&bytes, stem),
                "{path} names {stem}; the pickle must be the only thing that does"
            );
        }
    }

    /// A hand-transcribed byte stream is worth nothing if it is not a pickle.
    /// Checked structurally rather than by eye: the frame length is redundant
    /// with the file length and the string length prefixes are redundant with
    /// the strings, so a typo in any of them shows up here.
    #[test]
    fn the_blob_is_a_structurally_valid_protocol_4_pickle() {
        let (_dir, repo, _truth) = materialize();
        let blob = std::fs::read(repo.root().join(MECHANISM)).expect("read the cache blob");

        assert_eq!(&blob[..2], b"\x80\x04", "PROTO 4 header");
        assert_eq!(blob[2], 0x95, "protocol 4 opens the payload with FRAME");
        let frame = u64::from_le_bytes(blob[3..11].try_into().expect("8 frame-length bytes"));
        assert_eq!(
            frame as usize,
            blob.len() - 11,
            "the FRAME length must cover exactly the rest of the stream"
        );
        assert_eq!(blob.last(), Some(&b'.'), "STOP terminates every pickle");

        let mut last_end = 0;
        for name in ["pricing.legacy_rates", LIVE_CLASS] {
            let mut expected = vec![0x8c, name.len() as u8];
            expected.extend_from_slice(name.as_bytes());
            let at = blob
                .windows(expected.len())
                .position(|window| window == expected)
                .unwrap_or_else(|| {
                    panic!("expected SHORT_BINUNICODE {name:?} with a correct length prefix")
                });
            last_end = at + expected.len();
        }
        assert_eq!(
            &blob[last_end..last_end + 2],
            &[0x94, 0x93],
            "MEMOIZE then STACK_GLOBAL must follow the class name; STACK_GLOBAL is \
             the opcode that actually resolves it"
        );
    }

    /// §6.24's implementable counter-signals, so refusing here is something a
    /// tool could have decided rather than guessed.
    #[test]
    fn the_repository_admits_it_deserializes_and_the_type_carries_the_veto_marker() {
        let (_dir, repo, _truth) = materialize();
        let loader = std::fs::read(repo.root().join("pricing/cache.py")).expect("read the loader");
        assert!(
            mentions(&loader, "pickle"),
            "serializer detection is the counter-signal; import it for real"
        );
        let live = std::fs::read(repo.root().join(LIVE_MODULE)).expect("read the live module");
        assert!(
            mentions(&live, "__setstate__"),
            "§6.24 lists __setstate__ as a VETO marker on the candidate itself"
        );
    }

    /// "Does not break the build, does not break any test" (§6.24). Only true
    /// while nothing in the suite loads the committed blob.
    #[test]
    fn nothing_in_the_repository_constructs_or_unpickles_the_live_class() {
        let (_dir, repo, _truth) = materialize();
        for (path, bytes) in tree(repo.root()) {
            if !path.starts_with("tests/") {
                continue;
            }
            assert!(
                !mentions(&bytes, MECHANISM) && !mentions(&bytes, "quote-cache"),
                "{path} reads the committed blob; then deletion would break a test \
                 and m16 would not be m16"
            );
        }
    }

    #[test]
    fn the_decoy_is_named_by_nothing() {
        let (_dir, repo, truth) = materialize();
        for decoy in &truth.decoy_dead_paths {
            let stem = decoy
                .file_stem()
                .expect("decoy has a file name")
                .to_string_lossy()
                .into_owned();
            for (path, bytes) in tree(repo.root()) {
                if Path::new(&path) == decoy.as_path() {
                    continue;
                }
                assert!(
                    !mentions(&bytes, &stem),
                    "{path} references the decoy {stem:?}, so it is not dead"
                );
            }
        }
    }
}
